/**
 * Generate tests/fixtures/parity.json from the *JavaScript* implementation.
 *
 *   node tools/dump_parity.mjs [--out tests/fixtures/parity.json]
 *   GOLF_SRC=/path/to/golf/src/ node tools/dump_parity.mjs
 *
 * The fixture is the specification for the Python port: it is produced by running
 * the shipped rules, never by reading them. Do not hand-edit it; regenerate.
 *
 * The trailing slash on the GOLF_SRC URL matters: without it the last path segment
 * is treated as a file name and `new URL("engine.mjs", base)` resolves one level up.
 */
import { writeFileSync, mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const SRC = new URL(process.env.GOLF_SRC || "../../golf/src/", import.meta.url);
const engine = await import(new URL("engine.mjs", SRC).href);
const viewmod = await import(new URL("view.mjs", SRC).href);

const {
  RANKS, SUITS, COLS, HAND, HOLES, MIN_SEATS, MAX_SEATS,
  RuleError, apply, buildDeck, cardValue, createMatch, isRed, label, legalActions, makeRng, scoreHand, shuffle,
} = engine;

const outArg = process.argv.indexOf("--out");
const here = dirname(fileURLToPath(import.meta.url));
const outPath = resolve(here, "..", outArg > 0 ? process.argv[outArg + 1] : "tests/fixtures/parity.json");

const snap = (s) => ({
  hole: s.hole,
  holes: s.holes,
  dealer: s.dealer,
  turn: s.turn,
  phase: s.phase,
  ending: s.ending,
  turnsLeft: s.turnsLeft,
  over: s.over,
  endedBy: s.endedBy ?? null,
  seats: s.seats.map((x) => ({ name: x.name, total: x.total })),
  holeScores: s.holeScores,
  hands: s.hands.map((h) => h.map((c) => ({ rank: c.rank, suit: c.suit, up: c.up }))),
  stock: s.stock.map((c) => c.rank + c.suit),
  discard: s.discard.map((c) => c.rank + c.suit),
  pending: s.pending ? s.pending.rank + s.pending.suit : null,
  source: s.source,
  log: s.log.map((e) => ({ text: e.text, hl: e.hl, hole: e.hole })),
  legal: s.hands.map((_, i) => legalActions(s, i)),
});

/* ── the same deterministic policy the JS test suite uses ─────────────── */
function columnValue(hand, i) {
  const other = i < 3 ? i + 3 : i - 3;
  const value = (c) => (c.up ? cardValue(c.rank) : 5.5);
  return value(hand[i]) + value(hand[other]);
}
function bestGain(hand, card) {
  let best = -Infinity;
  let slot = 0;
  for (let i = 0; i < HAND; i++) {
    const other = i < 3 ? i + 3 : i - 3;
    const mate = hand[other].up ? cardValue(hand[other].rank) : 5.5;
    const gain = columnValue(hand, i) - (cardValue(card.rank) + mate);
    if (gain > best) { best = gain; slot = i; }
  }
  return { gain: best, slot };
}
function chooseAction(state, seat) {
  if (state.phase === "done") return state.over ? null : { type: "next-hole" };
  const hand = state.hands[seat];
  if (state.phase === "draw") {
    const top = state.discard[state.discard.length - 1];
    if (top && bestGain(hand, top).gain >= 3) return { type: "draw-discard" };
    return { type: "draw-stock" };
  }
  if (state.phase === "swap") {
    const { gain, slot } = bestGain(hand, state.pending);
    if (state.source === "stock" && gain <= 0) return { type: "discard" };
    return { type: "swap", slot };
  }
  throw new Error(`no action for phase ${state.phase}`);
}

const fixture = {
  meta: {
    source: "golf/src/engine.mjs + golf/src/view.mjs (JavaScript)",
    generated: new Date().toISOString(),
    note: "Generated by tools/dump_parity.mjs from the shipped JS rules. Do not hand-edit.",
  },
  constants: { RANKS, SUITS, COLS, HAND, HOLES, MIN_SEATS, MAX_SEATS },
  cardValue: Object.fromEntries(RANKS.map((r) => [r, cardValue(r)])),
  isRed: Object.fromEntries(SUITS.map((s) => [s, isRed(s)])),
  labels: buildDeck().map((c) => ({ rank: c.rank, suit: c.suit, label: label(c) })),
};

/* ── scoring: the full rank × rank grid for each column position ──────── */
{
  const cases = [];
  for (const ra of RANKS) {
    for (const rb of RANKS) {
      // slot 0 vs 3 is the pair under test; slots 1/4 and 2/5 are fixed non-pairs.
      const hand = [
        { rank: ra, suit: "♠" }, { rank: "6", suit: "♥" }, { rank: "7", suit: "♦" },
        { rank: rb, suit: "♣" }, { rank: "8", suit: "♥" }, { rank: "9", suit: "♠" },
      ];
      const { total, cols } = scoreHand(hand);
      cases.push({ hand, total, cols });
    }
  }
  // and a handful where all three columns pair, plus every rank paired with itself
  for (const r of RANKS) {
    const hand = [r, "3", "4", r, "3", "4"].map((rank) => ({ rank, suit: "♦" }));
    const { total, cols } = scoreHand(hand);
    cases.push({ hand, total, cols });
  }
  fixture.scoreHand = cases;
}

/* ── the random source, and the deck it produces ──────────────────────── */
fixture.rng = [0, 1, 7, 42, 99, 12345, 2147483648, 4294967295].map((seed) => {
  const rng = makeRng(seed);
  return { seed, values: Array.from({ length: 20 }, () => rng()) };
});
fixture.shuffle = [1, 7, 42].map((seed) => ({
  seed,
  order: shuffle(buildDeck(), makeRng(seed)).map((c) => c.rank + c.suit),
}));

/* ── deals: every seat count × a few seeds ───────────────────────────── */
fixture.deals = [];
for (const seats of [2, 3, 4]) {
  for (const seed of [1, 7, 42, 99, 2024]) {
    const state = createMatch({ seats, seed });
    fixture.deals.push({ seats, seed, state: snap(state) });
  }
}

/* ── scripted first holes: every action, in order, with the state after ─ */
fixture.scripted = [];
for (const [seats, seed] of [[2, 5], [3, 8], [3, 99], [4, 17], [2, 31], [4, 404]]) {
  const state = createMatch({ seats, seed });
  const steps = [];
  let guard = 0;
  while (state.phase !== "done" && guard++ < 400) {
    const seat = state.turn;
    const action = chooseAction(state, seat);
    apply(state, seat, action);
    steps.push({ seat, action, state: snap(state) });
  }
  fixture.scripted.push({ seats, seed, steps });
}

/* ── refusals: the exact message for every illegal move ──────────────── */
{
  // Every case records the state's construction (seats, seed, setup actions) so the
  // Python side can rebuild the identical state and compare only the *error*.
  const cases = [];
  const TURN = (s) => s.turn;
  const attempt = (name, seats, seed, setup, seatPick, action) => {
    const state = createMatch({ seats, seed });
    for (const a of setup) apply(state, state.turn, a);
    const seat = typeof seatPick === "function" ? seatPick(state) : seatPick;
    let error = null;
    try {
      apply(state, seat, action);
    } catch (e) {
      error = e.message;
    }
    cases.push({ name, seats, seed, setup, seat, action, error });
  };

  attempt("out of turn", 3, 3, [], (s) => (s.turn + 1) % 3, { type: "draw-stock" });
  attempt("unknown action", 2, 4, [], TURN, { type: "deal-me-an-ace" });
  attempt("null action", 2, 4, [], TURN, null);
  attempt("empty action", 2, 4, [], TURN, {});
  attempt("no such seat", 2, 4, [], 9, { type: "draw-stock" });
  attempt("negative seat", 2, 4, [], -1, { type: "draw-stock" });
  attempt("next-hole mid-hole", 2, 2, [], 0, { type: "next-hole" });
  attempt("throwing the taken discard back", 2, 11, [{ type: "draw-discard" }], TURN, { type: "discard" });
  attempt("swap before drawing", 2, 4, [], TURN, { type: "swap", slot: 6 });
  attempt("swap slot out of range", 2, 4, [{ type: "draw-stock" }], TURN, { type: "swap", slot: 6 });
  attempt("swap slot not an integer", 2, 4, [{ type: "draw-stock" }], TURN, { type: "swap", slot: 1.5 });
  attempt("swap slot a string", 2, 4, [{ type: "draw-stock" }], TURN, { type: "swap", slot: "3" });
  attempt("draw twice", 2, 4, [{ type: "draw-stock" }], TURN, { type: "draw-stock" });
  attempt("unknown after draw", 2, 4, [{ type: "draw-stock" }], TURN, { type: "flip", slot: 1 });
  fixture.refusals = cases;

  fixture.seatCountRefusals = [0, 1, 5, 6].map((seats) => {
    try {
      createMatch({ seats, seed: 1 });
      return { seats, error: null };
    } catch (e) {
      return { seats, error: e.message, isRuleError: e instanceof RuleError };
    }
  });
}

/* ── views: the redaction boundary on real states ────────────────────── */
fixture.views = [];
{
  const add = (name, seats, seed, setup, playTo = null) => {
    const state = createMatch({ seats, seed });
    const actions = [];
    for (const a of setup) {
      apply(state, state.turn, a);
      actions.push(a);
    }
    if (playTo) {
      let guard = 0;
      while (!playTo(state) && guard++ < 400) {
        const a = chooseAction(state, state.turn);
        apply(state, state.turn, a);
        actions.push(a);
      }
    }
    fixture.views.push({
      name,
      seats,
      seed,
      actions,
      state: snap(state),
      views: Array.from({ length: seats }, (_, seat) => viewmod.view(state, seat)),
    });
  };
  add("fresh deal", 3, 42, []);
  add("after a stock draw", 3, 6, [{ type: "draw-stock" }]);
  add("after taking the discard", 2, 15, [{ type: "draw-discard" }]);
  add("mid hole", 3, 18, [], (s) => s.turn === 2 && s.phase === "swap");
  add("hole scored", 3, 18, [], (s) => s.phase === "done");
  add("match over", 2, 31, [], (s) => s.over);
}

/* ── whole matches: totals, hole-by-hole scores, terminal state ───────── */
fixture.matches = [];
for (const [seats, seed] of [[2, 31], [3, 99], [3, 8], [4, 17]]) {
  const state = createMatch({ seats, seed });
  const history = [];
  const actions = [];
  let guard = 0;
  while (!state.over && guard++ < 20000) {
    const action = chooseAction(state, state.turn);
    apply(state, state.turn, action);
    actions.push(action);
    if (state.phase === "done") history.push({ hole: state.hole, holeScores: [...state.holeScores] });
  }
  fixture.matches.push({
    seats,
    seed,
    steps: guard,
    actions,
    history,
    final: snap(state),
  });
}

fixture.counts = {
  scoreHand: fixture.scoreHand.length,
  rng: fixture.rng.length,
  shuffle: fixture.shuffle.length,
  deals: fixture.deals.length,
  scripted: fixture.scripted.length,
  scriptedSteps: fixture.scripted.reduce((n, s) => n + s.steps.length, 0),
  refusals: fixture.refusals.length,
  views: fixture.views.length,
  matches: fixture.matches.length,
};

mkdirSync(dirname(outPath), { recursive: true });
writeFileSync(outPath, JSON.stringify(fixture, null, 1) + "\n");
console.log(`wrote ${outPath}`);
console.log(JSON.stringify(fixture.counts, null, 2));
