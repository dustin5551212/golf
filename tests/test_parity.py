"""Parity: the Python rules must answer exactly what the shipped JavaScript rules answer.

The fixture in ``tests/fixtures/parity.json`` is generated by
``tools/dump_parity.mjs`` from ``golf/src/*.mjs`` — the source implementation, not a
summary of it. Regenerate, never hand-edit:

    GOLF_SRC=/path/to/golf/src/ node tools/dump_parity.mjs

Every case here replays recorded actions against the Python engine and compares the
full canonical snapshot (see ``golf/snapshot.py``): score ladders, deck order, turn
order, log text, legal moves per seat, refusal messages and all nine holes of a match.
"""

from __future__ import annotations

import json
from pathlib import Path

import pytest

from golf import engine as E
from golf.snapshot import snapshot
from golf.view import view

FIXTURE = json.loads((Path(__file__).parent / "fixtures" / "parity.json").read_text(encoding="utf-8"))


def _first_difference(actual, expected, path="") -> str:
    """A readable report of the first divergence, instead of a 200-line dict diff."""
    if type(actual) is not type(expected):
        return f"{path or 'value'}: type {type(actual).__name__} != {type(expected).__name__} ({actual!r} vs {expected!r})"
    if isinstance(actual, dict):
        if set(actual) != set(expected):
            return f"{path}: keys {sorted(set(actual) ^ set(expected))} differ"
        for k in actual:
            sub = _first_difference(actual[k], expected[k], f"{path}.{k}" if path else k)
            if sub:
                return sub
        return ""
    if isinstance(actual, list):
        if len(actual) != len(expected):
            return f"{path}: length {len(actual)} != {len(expected)}"
        for i, (a, b) in enumerate(zip(actual, expected)):
            sub = _first_difference(a, b, f"{path}[{i}]")
            if sub:
                return sub
        return ""
    return "" if actual == expected else f"{path or 'value'}: {actual!r} != {expected!r}"


def assert_matches(actual, expected, where: str) -> None:
    diff = _first_difference(actual, expected)
    if diff:
        pytest.fail(f"{where}\n  {diff}")


def replay(seats: int, seed: int, actions: list) -> E.State:
    state = E.create_match(seats=seats, seed=seed)
    for action in actions:
        E.apply(state, state.turn, action)
    return state


# ── the fixture must stay worth comparing against ───────────────────────


def test_fixture_has_every_section_and_is_not_shrunken():
    counts = FIXTURE["counts"]
    assert counts["scoreHand"] >= 180, "scoring matrix lost cases"
    assert counts["rng"] >= 8
    assert counts["shuffle"] >= 3
    assert counts["deals"] >= 15
    assert counts["scriptedSteps"] >= 300
    assert counts["refusals"] >= 12
    assert counts["views"] >= 6
    assert counts["matches"] >= 4
    for match in FIXTURE["matches"]:
        assert match["actions"], "a whole match with no recorded actions proves nothing"


# ── constants, labels, scoring ──────────────────────────────────────────


def test_constants_match_the_source():
    c = FIXTURE["constants"]
    assert E.RANKS == c["RANKS"]
    assert E.SUITS == c["SUITS"]
    assert [list(x) for x in E.COLS] == c["COLS"]
    assert (E.HAND, E.HOLES, E.MIN_SEATS, E.MAX_SEATS) == (c["HAND"], c["HOLES"], c["MIN_SEATS"], c["MAX_SEATS"])


def test_card_values_match_for_every_rank():
    for rank, expected in FIXTURE["cardValue"].items():
        assert E.card_value(rank) == expected, f"card_value({rank})"


def test_red_suits_match():
    for suit, expected in FIXTURE["isRed"].items():
        assert E.is_red(suit) is expected, f"is_red({suit})"


def test_every_card_label_matches():
    for case in FIXTURE["labels"]:
        assert E.label({"rank": case["rank"], "suit": case["suit"]}) == case["label"]


def test_scoring_grid_matches_for_every_rank_pair():
    for i, case in enumerate(FIXTURE["scoreHand"]):
        got = E.score_hand(case["hand"])
        assert_matches(got["total"], case["total"], f"scoreHand[{i}] total for {case['hand'][0]['rank']}/{case['hand'][3]['rank']}")
        assert_matches(got["cols"], case["cols"], f"scoreHand[{i}] cols for {case['hand'][0]['rank']}/{case['hand'][3]['rank']}")


# ── the random source and the deck it deals ─────────────────────────────


def test_rng_produces_the_same_stream_for_every_seed():
    for case in FIXTURE["rng"]:
        rng = E.make_rng(case["seed"])
        got = [rng() for _ in case["values"]]
        assert_matches(got, case["values"], f"mulberry32 stream for seed {case['seed']}")


def test_shuffle_orders_the_deck_identically():
    for case in FIXTURE["shuffle"]:
        deck = E.shuffle(E.build_deck(), E.make_rng(case["seed"]))
        assert_matches([c["rank"] + c["suit"] for c in deck], case["order"], f"shuffle for seed {case['seed']}")


# ── deals, scripted holes, refusals, views, whole matches ───────────────


def test_every_dealt_position_matches():
    for case in FIXTURE["deals"]:
        state = E.create_match(seats=case["seats"], seed=case["seed"])
        assert_matches(snapshot(state), case["state"], f"deal {case['seats']} seats seed {case['seed']}")


def test_every_recorded_hole_step_matches():
    for case in FIXTURE["scripted"]:
        state = E.create_match(seats=case["seats"], seed=case["seed"])
        for n, step in enumerate(case["steps"]):
            E.apply(state, step["seat"], step["action"])
            assert_matches(
                snapshot(state),
                step["state"],
                f"{case['seats']} seats seed {case['seed']}, step {n + 1} after {step['action']}",
            )


def test_every_refusal_says_exactly_what_the_source_says():
    for case in FIXTURE["refusals"]:
        state = E.create_match(seats=case["seats"], seed=case["seed"])
        for action in case["setup"]:
            E.apply(state, state.turn, action)
        with pytest.raises(E.RuleError) as excinfo:
            E.apply(state, case["seat"], case["action"])
        assert str(excinfo.value) == case["error"], f"refusal '{case['name']}'"


def test_seat_counts_outside_two_to_four_are_refused_with_the_same_message():
    for case in FIXTURE["seatCountRefusals"]:
        with pytest.raises(E.RuleError) as excinfo:
            E.create_match(seats=case["seats"], seed=1)
        assert str(excinfo.value) == case["error"]


def test_every_recorded_view_matches_seat_by_seat():
    for case in FIXTURE["views"]:
        state = replay(case["seats"], case["seed"], case["actions"])
        assert_matches(snapshot(state), case["state"], f"view setup '{case['name']}' (engine state)")
        for seat, expected in enumerate(case["views"]):
            assert_matches(view(state, seat), expected, f"view '{case['name']}', seat {seat}")


def test_every_whole_match_ends_in_the_same_place():
    for case in FIXTURE["matches"]:
        state = E.create_match(seats=case["seats"], seed=case["seed"])
        history = []
        for action in case["actions"]:
            E.apply(state, state.turn, action)
            if state.phase == "done":
                history.append({"hole": state.hole, "holeScores": list(state.hole_scores)})
        assert_matches(history, case["history"], f"{case['seats']} seats seed {case['seed']} hole-by-hole scores")
        assert_matches(snapshot(state), case["final"], f"{case['seats']} seats seed {case['seed']} final state")
